function render(text: string): string[] {
  const matrix = encodeQr(text);
  return matrix.modules.map((row) => row.map((cell) => (cell ? "1" : "0")).join(""));
}

describe("encodeQr", () => {
  for (const fixture of FIXTURES) {
    it(`matches the reference encoder for ${fixture.name}`, () => {
      const matrix = encodeQr(fixture.text);
      expect(matrix.version).toBe(fixture.version);
      expect(matrix.size).toBe(fixture.rows.length);
      expect(render(fixture.text)).toEqual(fixture.rows);
    });
  }

  it("keeps the three finder patterns intact", () => {
    const { modules, size } = encodeQr("0xdeadbeef");
    for (const [row, col] of [
      [0, 0],
      [0, size - 7],
      [size - 7, 0],
    ]) {
      expect(modules[row][col]).toBe(true);
      expect(modules[row + 1][col + 1]).toBe(false);
      expect(modules[row + 3][col + 3]).toBe(true);
    }
  });

  it("refuses a payload that cannot fit", () => {
    expect(() => encodeQr("x".repeat(MAX_QR_BYTES + 1))).toThrow(/too long/);
  });

  it("emits one path square per dark module", () => {
    const matrix = encodeQr("hi");
    const dark = matrix.modules.flat().filter(Boolean).length;
    expect(qrPath(matrix).split("M").length - 1).toBe(dark);
  });
});
